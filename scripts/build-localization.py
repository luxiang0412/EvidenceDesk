def build() -> dict:
    strings = {}
    for key, value in ZH.items():
        strings[key] = {
            "extractionState": "manual",
            "localizations": {
                "zh-Hans": {"stringUnit": {"state": "translated", "value": value}}
            },
        }
    for key, value in ZH_FORMAT.items():
        strings[key] = {
            "extractionState": "manual",
            "localizations": {
                "zh-Hans": {"stringUnit": {"state": "translated", "value": value}}
            },
        }
    return {
        "sourceLanguage": "en",
        "strings": dict(sorted(strings.items())),
        "version": "1.0",
    }


if __name__ == "__main__":
    out = Path(__file__).resolve().parent.parent / "EvidenceDesk/Resources/Localizable.xcstrings"
    out.write_text(json.dumps(build(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out} with {len(ZH) + len(ZH_FORMAT)} entries")
